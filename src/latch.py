"""Exact lattice fusion of integer vectors using a threshold-pattern min cut.

The fusion routine deliberately takes no constraint matrix or cost matrix.
It maximizes a linear objective over the sublattice generated by its inputs.
"""
from collections import deque
from dataclasses import dataclass
import numpy as np
from scipy.sparse import csr_matrix
from scipy.sparse.csgraph import maximum_flow


@dataclass
class Fusion:
    vector: np.ndarray
    value: int
    selected_masks: list
    masks: list
    weights: list
    cut_value: int
    base_value: int
    implication_count: int


def fuse(vectors, coefficients):
    """Return the best min/max expression in the input vectors.

    vectors has shape (K,d). Values and objective coefficients are integral.
    SciPy's flow backend is guarded by a conservative 30-bit capacity limit.
    Inputs may be arbitrary vectors; feasibility is inherited when their common
    feasible region is closed under coordinatewise min and max.
    """
    z = np.asarray(vectors)
    a = np.asarray(coefficients)
    if z.ndim != 2 or len(z) < 1 or a.shape != (z.shape[1],):
        raise ValueError('Expected nonempty K by d vectors and d coefficients')
    if not np.issubdtype(z.dtype, np.integer) or not np.issubdtype(a.dtype, np.integer):
        raise TypeError('This reference implementation requires integer inputs')
    if len(z) > 20:
        raise ValueError('At most 20 predictors supported by this implementation')
    k,d=z.shape
    # Guard all NumPy arithmetic, then form threshold masks in one sorted pass.
    limit=max([1]+[abs(int(v)) for v in z.ravel()])
    coef=max([1]+[abs(int(v)) for v in a])
    if 4*d*k*limit*coef >= 2**60:
        raise OverflowError('integer arithmetic guard')
    order=np.argsort(z,axis=0,kind='stable')
    values=np.take_along_axis(z,order,axis=0)
    base=sum(int(x)*int(y) for x,y in zip(a,values[0]))
    masks_by_level=np.bitwise_or.accumulate((1<<order)[::-1],axis=0)[::-1][1:]
    deltas=np.diff(values,axis=0)
    nonzero=deltas!=0
    present,inverse=np.unique(masks_by_level[nonzero],return_inverse=True)
    totals=np.zeros(len(present),dtype=np.int64)
    np.add.at(totals,inverse,(deltas*a[None,:])[nonzero])
    weights={int(m):int(w) for m,w in zip(present,totals)}
    masks=sorted(weights); index={m:i for i,m in enumerate(masks)}
    n=len(masks); source=n; sink=n+1
    infinity=1+sum(abs(x) for x in weights.values())
    if infinity >= 2**30:
        raise OverflowError('Flow capacity guard: rescale inputs or use exact flow backend')
    rows=[];cols=[];caps=[]
    def edge(i,j,c):
        if c:
            rows.append(i);cols.append(j);caps.append(c)
    positive=0
    for m in masks:
        w=weights[m]
        if w>0:
            edge(source,index[m],w);positive+=w
        elif w<0:
            edge(index[m],sink,-w)
    implications=0
    for s in masks:
        for t in masks:
            if s != t and s & t == s:
                edge(index[s],index[t],infinity); implications+=1
    capacity=csr_matrix((caps,(rows,cols)),shape=(n+2,n+2),dtype=np.int64)
    flow=maximum_flow(capacity,source,sink,method='dinic')
    residual=(capacity-flow.flow).tocsr()
    seen={source};queue=deque([source])
    while queue:
        v=queue.popleft()
        for ix in range(residual.indptr[v],residual.indptr[v+1]):
            j=int(residual.indices[ix])
            if residual.data[ix]>0 and j not in seen:
                seen.add(j);queue.append(j)
    chosen={m for m in masks if index[m] in seen}
    selected=np.isin(masks_by_level,list(chosen))
    vector=values[0]+np.sum(deltas*selected,axis=0)
    value=sum(int(x)*int(y) for x,y in zip(a,vector))
    assert value==base+positive-int(flow.flow_value)
    assert all(t in chosen for s in chosen for t in masks if s & t == s)
    return Fusion(vector,value,sorted(chosen),masks,[weights[m] for m in masks],
                  int(flow.flow_value),base,implications)


def expression(vectors, selected_masks):
    """Independently reconstruct max_S min_{h in S} z^h, including S=[K]."""
    z=np.asarray(vectors);k=len(z)
    masks=set(selected_masks)|{(1<<k)-1}
    return np.max([np.min(z[[h for h in range(k) if m>>h&1]],axis=0)
                   for m in masks],axis=0)


def repair(cost,u):
    """Standard one-sided dual completion (Min-Trick), not a new method."""
    u=np.asarray(u,dtype=np.int64)
    v=np.min(cost-u[:,None],axis=0)
    return np.concatenate((u,-v))


def feasible(cost,z):
    n=len(cost)
    return bool(np.all(z[:n,None]-z[None,n:]<=cost))


def hungarian(cost,seed=None):
    """Dense exact shortest-augmenting-path Hungarian reference, integer costs.

    Starts from any feasible (u,-v). Returns assignment, dual and inner loops.
    This readable Python solver is not a competitive production backend.
    """
    cost=np.asarray(cost,dtype=np.int64);n=len(cost)
    if cost.shape != (n,n):
        raise ValueError('square cost matrix required')
    if seed is None:
        u=np.zeros(n+1,dtype=np.int64);v=np.zeros(n+1,dtype=np.int64)
        u[1:]=np.min(cost,axis=1)
    else:
        if not feasible(cost,seed): raise ValueError('infeasible seed')
        u=np.r_[0,seed[:n]].copy();v=np.r_[0,-seed[n:]].copy()
    p=np.zeros(n+1,dtype=int);way=np.zeros(n+1,dtype=int);loops=0;updates=0
    for i in range(1,n+1):
        p[0]=i;j0=0;minv=np.full(n+1,2**60,dtype=np.int64)
        used=np.zeros(n+1,dtype=bool)
        while True:
            loops+=1;used[j0]=True;i0=p[j0]
            unused=np.flatnonzero(~used[1:])+1
            cur=cost[i0-1,unused-1]-u[i0]-v[unused]
            improve=cur<minv[unused]
            js=unused[improve];minv[js]=cur[improve];way[js]=j0
            j1=int(unused[np.argmin(minv[unused])]);delta=int(minv[j1])
            if delta>0: updates+=1
            u[p[used]]+=delta;v[used]-=delta;minv[~used]-=delta
            j0=j1
            if p[j0]==0:break
        while True:
            j1=way[j0];p[j0]=p[j1];j0=j1
            if j0==0:break
    assignment=np.empty(n,dtype=int)
    for j in range(1,n+1):assignment[p[j]-1]=j-1
    z=np.r_[u[1:],-v[1:]]
    assert feasible(cost,z)
    assert int(cost[np.arange(n),assignment].sum())==int(u[1:].sum()+v[1:].sum())
    return assignment,z,dict(loops=loops,updates=updates)
